// Writes src/keys/glyphs.ts: Figtree (the app's font) as vector outlines. The
// keys are drawn as SVG, and Stream Deck would fall back to a system font for
// real text unless Figtree happens to be installed. Run once; the output is
// committed.
import fs from "node:fs";
import { createRequire } from "node:module";
import * as fontkit from "fontkit";

const require = createRequire(import.meta.url);
const CHARS =
  "0123456789 .,/%#+-–…':" + "ABCDEFGHIJKLMNOPQRSTUVWXYZ" + "abcdefghijklmnopqrstuvwxyz" + "é";
const WEIGHTS = [700, 800];
const EM = 1000;

// Figtree has no gender signs, and Nidoran needs them. Drawn by hand, in the
// same units: a ring with a cross, and a ring with an arrow.
const RING = (x: number, y: number) =>
  `M${x} ${y - 230}A230 230 0 1 1 ${x} ${y + 230}A230 230 0 1 1 ${x} ${y - 230}Z` +
  `M${x} ${y - 130}A130 130 0 1 0 ${x} ${y + 130}A130 130 0 1 0 ${x} ${y - 130}Z`;
const SIGNS = [
  `    "♀": { w: 560, d: "${RING(280, -470)}M230 -250H330V20H230ZM130 -130H430V-40H130Z" },`,
  `    "♂": { w: 660, d: "${RING(250, -250)}M365 -435L525 -595L595 -525L435 -365ZM340 -690H630V-400H530V-590H340Z" },`,
];

const tables = WEIGHTS.map((weight) => {
  const file = require.resolve(`@fontsource/figtree/files/figtree-latin-${weight}-normal.woff2`);
  const font = fontkit.openSync(file) as fontkit.Font;
  const scale = EM / font.unitsPerEm;
  const glyphs = [...CHARS].map((char) => {
    const glyph = font.glyphForCodePoint(char.codePointAt(0)!);
    const d = glyph.path
      .scale(scale, -scale)
      .toSVG()
      .replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));
    return `    ${JSON.stringify(char)}: { w: ${Math.round(glyph.advanceWidth * scale)}, d: ${JSON.stringify(d)} },`;
  });
  return `  ${weight}: {\n${[...glyphs, ...SIGNS].join("\n")}\n  },`;
});

fs.writeFileSync(
  "src/keys/glyphs.ts",
  `// Generated by scripts/make-glyphs.ts from Figtree, Copyright 2022 The Figtree Project
// Authors, under the SIL Open Font License (see THIRD-PARTY-LICENSES.md). Don't edit.
// Sizes are in thousandths of an em, y pointing down from the baseline.
export const GLYPHS: Record<number, Record<string, { w: number; d: string }>> = {
${tables.join("\n")}
};
`,
);
console.log("Wrote src/keys/glyphs.ts");
